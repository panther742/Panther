// Set of loaded fonts to prevent redundant link tags
const loadedFontLinks = new Set<string>();

/**
 * Dynamically injects a Google Font <link> into document <head>
 */
export function loadGoogleFont(family: string, weights: number[] = [300, 400, 500, 600, 700, 800, 900]): void {
  if (!family || typeof document === 'undefined') return;

  const fontKey = `${family}:${weights.join(',')}`;
  if (loadedFontLinks.has(fontKey)) return;

  try {
    const formattedFamily = family.replace(/\s+/g, '+');
    const weightsParam = weights.join(';');
    const fontUrl = `https://fonts.googleapis.com/css2?family=${formattedFamily}:ital,wght@0,${weightsParam};1,${weightsParam}&display=swap`;

    // Check if link element already exists
    const existingLink = document.querySelector(`link[href="${fontUrl}"]`);
    if (!existingLink) {
      const link = document.createElement('link');
      link.rel = 'stylesheet';
      link.href = fontUrl;
      document.head.appendChild(link);
    }

    loadedFontLinks.add(fontKey);
  } catch (err) {
    console.warn('Failed to load Google Font dynamically:', family, err);
  }
}

