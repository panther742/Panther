/**
 * Generate CSS Code for a Typography Pairing
 */
export function generatePairingCSS(pairing: TypographyPairing): string {
  const roles: FontRole[] = ['heading', 'subheading', 'body', 'caption', 'button', 'navigation'];
  let css = `/* Panther Typo Studio - ${pairing.name} (${pairing.style.toUpperCase()}) */\n\n`;

  roles.forEach((role) => {
    const config = pairing.roles[role];
    if (!config) return;
    css += `/* ${role.toUpperCase()} STYLING */\n`;
    css += `.${role}-text {\n`;
    css += `  font-family: '${config.fontFamily}', sans-serif;\n`;
    css += `  font-weight: ${config.fontWeight};\n`;
    css += `  font-size: ${config.fontSize}px;\n`;
    css += `  letter-spacing: ${config.letterSpacing}px;\n`;
    css += `  line-height: ${config.lineHeight};\n`;
    css += `  text-align: ${config.textAlign};\n`;
    if (config.textTransform !== 'none') {
      css += `  text-transform: ${config.textTransform};\n`;
    }
    if (config.fontStyle !== 'normal') {
      css += `  font-style: ${config.fontStyle};\n`;
    }
    if (config.color) {
      css += `  color: ${config.color};\n`;
    }
    css += `}\n\n`;
  });

  return css;
}

/**
 * Generate Google Fonts HTML Link Tag
 */
export function generateGoogleFontsLink(pairing: TypographyPairing): string {
  const families = new Set<string>();

  Object.values(pairing.roles).forEach((role) => {
    if (role.fontFamily) {
      families.add(role.fontFamily);
    }
  });

  const formattedFamilies = Array.from(families)
    .map((f) => `family=${f.replace(/\s+/g, '+')}:wght@300;400;500;600;700;800;900`)
    .join('&');

  return `<link rel="preconnect" href="https://fonts.googleapis.com">\n<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>\n<link href="https://fonts.googleapis.com/css2?${formattedFamilies}&display=swap" rel="stylesheet">`;
}

/**
 * Generate Google Fonts CSS @import
 */
export function generateGoogleFontsImport(pairing: TypographyPairing): string {
  const families = new Set<string>();

  Object.values(pairing.roles).forEach((role) => {
    if (role.fontFamily) {
      families.add(role.fontFamily);
    }
  });

  const formattedFamilies = Array.from(families)
    .map((f) => `family=${f.replace(/\s+/g, '+')}:wght@300;400;500;600;700;800;900`)
    .join('&');

  return `@import url('https://fonts.googleapis.com/css2?${formattedFamilies}&display=swap');`;
}

/**
 * Generate Markdown Brand Guide / Specimen Sheet
 */
export function generateTypographyBrandGuide(pairing: TypographyPairing): string {
  let md = `# PANTHER STUDIO - TYPOGRAPHY SPECIMEN GUIDE\n\n`;
  md += `**Style Theme:** ${pairing.name} (${pairing.style.toUpperCase()})\n`;
  md += `**Background Color:** \`${pairing.bgColor}\`\n\n`;
  md += `--- \n\n`;
  md += `## Font Hierarchy & Specifications\n\n`;

  const roles: FontRole[] = ['heading', 'subheading', 'body', 'caption', 'button', 'navigation'];

  roles.forEach((role) => {
    const config = pairing.roles[role];
    md += `### ${role.toUpperCase()}\n`;
    md += `- **Font Family:** ${config.fontFamily}\n`;
    md += `- **Weight:** ${config.fontWeight}\n`;
    md += `- **Size:** ${config.fontSize}px\n`;
    md += `- **Letter Spacing:** ${config.letterSpacing}px\n`;
    md += `- **Line Height:** ${config.lineHeight}\n`;
    md += `- **Color:** \`${config.color}\`\n\n`;
  });

  md += `## Google Fonts Import Link\n\n`;
  md += `\`\`\`html\n${generateGoogleFontsLink(pairing)}\n\`\`\`\n\n`;

  md += `## CSS Rules\n\n`;
  md += `\`\`\`css\n${generatePairingCSS(pairing)}\n\`\`\`\n`;

  return md;
}
